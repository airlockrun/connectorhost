#!/usr/bin/env bash
set -euo pipefail

output="${1:?usage: gen-notices.sh OUTPUT}"
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
modules="$(mktemp)"
trap 'rm -f "$modules"' EXIT

cd "$root"
GOWORK=off go list -deps -f '{{with .Module}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}' ./cmd/airlock-host |
  LC_ALL=C sort -u > "$modules"

{
  printf '# Third-party notices — airlock-host\n\n'
  printf 'Generated by scripts/gen-notices.sh from the compiled host dependency graph.\n\n'
  printf '## Go standard library %s\n\n' "$(GOWORK=off go env GOVERSION)"
  cat "$(GOWORK=off go env GOROOT)/LICENSE"
  while IFS='|' read -r path version directory; do
    [[ -z "$path" || "$path" == github.com/airlockrun/connectorhost ]] && continue
    license=""
    for candidate in "$directory"/LICENSE* "$directory"/COPYING* "$directory"/LICENCE*; do
      if [[ -f "$candidate" ]]; then
        license="$candidate"
        break
      fi
    done
    if [[ -z "$license" ]]; then
      printf 'missing dependency license: %s\n' "$path" >&2
      exit 1
    fi
    printf '\n## %s %s\n\n' "$path" "$version"
    cat "$license"
    for notice in "$directory"/NOTICE*; do
      [[ -f "$notice" ]] || continue
      printf '\n### NOTICE\n\n'
      cat "$notice"
    done
  done < "$modules"
} > "$output"
